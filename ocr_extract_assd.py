FIELDS = ["ac_part", "vidhan_sabha_name", "bhag_sankhya_name", "serial_no", "epic_number", "voter_name",
          "relation_type", "relation_name", "old_part_no", "old_serial_no", "age", "gender", "reason", "review"]
COLS = ["serial_no", "epic_number", "voter_name", "relation_type", "relation_name",
        "old_part_no", "old_serial_no", "age", "gender", "reason"]          # the 10 table columns, left to right

REL_OK = {"पिता", "पति", "माता", "माँ", "अन्य", "पत्नी", "भाई", "बहन", "पुत्र", "पुत्री"}
