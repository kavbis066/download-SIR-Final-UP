#!/usr/bin/env python3
"""
ocr_extract_assd.py (a1) -- "uncollectable elector" (ASD) report tables -> one CSV per AC.

Input layout     ASDD/output/AC_<ac>/ac<ac>_part<N>.pdf
Output           out_assd/<ac>/<ac>_assd.csv        (split into <ac>_assd_001.csv ... at 100,000 rows)
                 out_assd/<ac>/_run_info.json

Columns
  ac_part                 "<ac>_<part>", e.g. 1_1  (same format as the card CSVs)
  vidhan_sabha_name       line 1 of the PDF after the colon      ->  "1 - बेहट"
  bhag_sankhya_name       line 2 of the PDF after the colon      ->  "1 - उच्च प्राथमिक विद्यालय कक्ष नम्बर 1, रहना"
  serial_no               क्रम संख्या
  epic_number             मतदाता फोटो पहचान पत्र संख्या  (the key to match against out_deleted epic_no)
  voter_name              मतदाता का नाम
  relation_type           संबंध का प्रकार
  relation_name           संबंधी का नाम
  old_part_no             पुरानी भाग संख्या
  old_serial_no           पुरानी भाग का क्रम संख्या
  age                     आयु
  gender                  लिंग
  reason                  गणना प्रपत्र प्राप्त न होने का कारण
  review                  empty when every check passed, otherwise what to look at (see CHECKS below)

HOW THE TABLE IS READ
  These PDFs are generated by the ECI software, NOT scanned: every page carries a real text layer. Reading that
  layer gives the exact characters that were printed (EPIC numbers and names included), which no OCR can match,
  so it is the default (--mode auto). The layer needs one repair: the font puts a duplicate glyph behind every
  half-form conjunct (मुस्तफा comes out as मुस्<ZWJ>ततफा, प्राथमिक as प्रााथमिक), which is removed using the glyph
  widths. Text that is printed wrongly in the source (e.g. बि्रहम, सेफमलुक) is kept as printed -- it is the record.
  A page without a text layer (a scanned copy) is read by OCR instead: the table grid is found with OpenCV, every
  cell is cropped, and the same PaddleOCR v5 + v3 models as the card scripts read it (--mode ocr forces this).

CHECKS (the `review` column)
  serial_gap        serial is not previous+1 inside the part
  epic_format       not AAA9999999 and not UP/<n>/<n>/<n>
  relation_type / gender / age / old_part_no / old_serial_no / name_missing / name_chars  -- field looks wrong
  ocr_low_conf      (OCR mode only) a name was read with a score below 0.90

USAGE
  python ocr_extract_assd.py --root ASDD/output --out out_assd --only 1 2 3
  python ocr_extract_assd.py --root ASDD/output --out out_assd --only-file acs.txt
  python ocr_extract_assd.py --root ASDD/output --out out_assd                 # every AC folder under assd/
  python ocr_extract_assd.py --pdf ASDD/output/AC_001/ac1_part1.pdf --out out_assd   # one file
"""
